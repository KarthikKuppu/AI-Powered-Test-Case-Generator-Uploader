/**
 * adoClient.js — Azure DevOps REST API wrapper
 *
 * Handles all communication with the ADO Work Item Tracking (WIT) API:
 *   - Reading a User Story and its acceptance criteria
 *   - Creating a Test Case work item
 *   - Linking a Test Case back to its User Story
 *
 * Credentials are read from environment variables set in .env:
 *   ADO_ORG_URL  — e.g. https://yourorg.visualstudio.com
 *   ADO_PROJECT  — e.g. Amethyst
 *   ADO_PAT      — Personal Access Token with Work Items + Test Management read/write
 */

const axios = require('axios');
require('dotenv').config();

// ── ADO connection config ────────────────────────────────────────────────────

const ORG_URL = process.env.ADO_ORG_URL;   // Base URL of your ADO organisation
const PROJECT = process.env.ADO_PROJECT;    // ADO project name
const PAT     = process.env.ADO_PAT;        // Personal Access Token

// ADO uses HTTP Basic auth where the username is empty and the password is the PAT.
// The combined string ":PAT" is Base64-encoded and sent in the Authorization header.
const AUTH = Buffer.from(`:${PAT}`).toString('base64');

// Default headers used for standard GET requests (Content-Type: application/json)
const baseHeaders = {
  Authorization: `Basic ${AUTH}`,
  'Content-Type': 'application/json',
};

// ── Functions ────────────────────────────────────────────────────────────────

/**
 * Fetches a User Story work item from ADO by its numeric ID, including the discussion
 * (comments) thread. Both calls are made in parallel to minimise latency.
 *
 * Discussion comments are included because they often contain clarifications from BAs,
 * design decisions, or scope changes that are critical context for writing accurate tests.
 *
 * @param {string|number} workItemId - The ADO work item ID (e.g. 51287)
 * @returns {object} - Story object: { id, title, description, acceptanceCriteria, state, discussion }
 */
async function getUserStory(workItemId) {
  const itemUrl       = `${ORG_URL}/${PROJECT}/_apis/wit/workitems/${workItemId}?$expand=all&api-version=7.1`;

  // Comments use the preview API (7.1-preview.3) — the stable endpoint does not exist yet
  // .catch() fallback returns an empty list so a missing comments permission does not abort the run
  const commentsUrl   = `${ORG_URL}/${PROJECT}/_apis/wit/workitems/${workItemId}/comments?api-version=7.1-preview.3`;

  // Fetch work item fields and discussion comments at the same time
  const [itemRes, commentsRes] = await Promise.all([
    axios.get(itemUrl, { headers: baseHeaders }),
    axios.get(commentsUrl, { headers: baseHeaders }).catch(() => ({ data: { comments: [] } })),
  ]);

  // All work item fields are nested under res.data.fields using ADO's field reference names
  const f        = itemRes.data.fields;

  // Format each comment as "[Author on DD/MM/YYYY]: text" so the AI has clear attribution
  const comments = commentsRes.data.comments || [];
  const discussion = comments
    .map(c => {
      const author = c.createdBy?.displayName || 'Unknown';
      const date   = new Date(c.createdDate).toLocaleDateString('en-GB');
      return `[${author} on ${date}]: ${c.text}`;
    })
    .join('\n\n');

  return {
    id:                 workItemId,
    title:              f['System.Title']                             || '',
    description:        f['System.Description']                       || '',
    acceptanceCriteria: f['Microsoft.VSTS.Common.AcceptanceCriteria'] || '',
    state:              f['System.State']                             || '',
    discussion:         discussion || '',   // Combined comment thread — empty string if no comments
  };
}

/**
 * Creates a new Test Case work item in ADO.
 *
 * ADO work items are created/updated using JSON Patch operations (RFC 6902).
 * Each field change is an operation object: { op, path, value }
 * The Content-Type must be "application/json-patch+json" — NOT plain JSON.
 *
 * @param {string} title       - Test case title (displayed in ADO)
 * @param {string} stepsXml    - Test steps in ADO XML format (generated by formatter.js)
 * @param {string} description - Plain-text or HTML description of what the test covers
 * @param {string|null} areaPath - Optional ADO area path (e.g. "Amethyst\\QA Team"). Uses project default if null.
 * @returns {number} - The new test case's ADO work item ID
 */
async function createTestCase(title, stepsXml, description, areaPath) {
  // $Test%20Case is the URL-encoded work item type name for "Test Case"
  const url = `${ORG_URL}/${PROJECT}/_apis/wit/workitems/$Test%20Case?api-version=7.1`;

  // Build the patch body with the required fields
  const body = [
    { op: 'add', path: '/fields/System.Title',             value: title       }, // Test case title
    { op: 'add', path: '/fields/Microsoft.VSTS.TCM.Steps', value: stepsXml    }, // Steps XML
    { op: 'add', path: '/fields/System.Description',       value: description }, // Description
  ];

  // Only add AreaPath if one was provided in input.json — omitting it lets ADO use the project default
  if (areaPath) {
    body.push({ op: 'add', path: '/fields/System.AreaPath', value: areaPath });
  }

  const res = await axios.post(url, body, {
    headers: {
      Authorization:  `Basic ${AUTH}`,
      'Content-Type': 'application/json-patch+json', // Required for work item patch operations
    },
  });

  // Return the newly created work item's ID so it can be linked to the user story
  return res.data.id;
}

/**
 * Links a Test Case to a User Story in ADO using the "Tested By" relationship.
 *
 * The relation type "Microsoft.VSTS.Common.TestedBy-Reverse" means:
 *   "this test case tests that user story"
 * which is the standard way to associate tests with requirements in ADO.
 *
 * After this call the test case will appear on the User Story's Tests tab in ADO.
 *
 * @param {number} testCaseId - ADO work item ID of the test case to link
 * @param {number} storyId    - ADO work item ID of the user story to link to
 */
async function linkTestCaseToStory(testCaseId, storyId) {
  // PATCH the test case work item to add the relationship
  const url = `${ORG_URL}/${PROJECT}/_apis/wit/workitems/${testCaseId}?api-version=7.1`;

  const body = [
    {
      op:   'add',
      path: '/relations/-',  // "-" appends a new relation to the existing list
      value: {
        rel: 'Microsoft.VSTS.Common.TestedBy-Reverse', // Relation type: "Tests" (from the test case's perspective)
        url: `${ORG_URL}/_apis/wit/workItems/${storyId}`, // URL of the user story work item
        attributes: { comment: 'Linked by ADO Test Agent' }, // Audit comment visible in ADO history
      },
    },
  ];

  await axios.patch(url, body, {
    headers: {
      Authorization:  `Basic ${AUTH}`,
      'Content-Type': 'application/json-patch+json', // Required for work item patch operations
    },
  });
}

module.exports = { getUserStory, createTestCase, linkTestCaseToStory };
